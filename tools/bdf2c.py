#!/usr/bin/env python3
"""Convert an 8x16 BDF font (e.g. Spleen) to kernel/font.c (ASCII 32..126)."""
import sys

glyphs, code, rows, in_bitmap = {}, None, [], False
for line in open(sys.argv[1], encoding="latin-1"):
    w = line.split()
    if not w:
        continue
    if w[0] == "ENCODING":
        code = int(w[1])
    elif w[0] == "BITMAP":
        in_bitmap, rows = True, []
    elif w[0] == "ENDCHAR":
        in_bitmap = False
        glyphs[code] = (rows + [0] * 16)[:16]
    elif in_bitmap:
        rows.append(int(w[0], 16) & 0xFF)

print("/* Generated by tools/bdf2c.py from Spleen 8x16 (BSD 2-Clause,")
print(" * Copyright (c) 2018-2026 Frederic Cambus). See third_party/SPLEEN-LICENSE. */")
print('#include "kernel.h"\n')
print("const u8 font8x16[95][16] = {")
for c in range(32, 127):
    data = ",".join("0x%02x" % b for b in glyphs[c])
    print("    {%s}, /* %s */" % (data, repr(chr(c))))
print("};")
